const it = testEffect(makeHttp() as unknown as Layer.Layer<never, any>)

const assistantCount = (messages: readonly { info: { role: string } }[]) =>
  messages.filter((message) => message.info.role === "assistant").length

// H1 survival: every tool round of one assistant turn must ride inside a single
// provider invocation instead of reopening one `streamText` per round.
it.instance(
  "chains N tool rounds inside a single provider invocation",
  () =>
    Effect.gen(function* () {
      const { llm } = yield* useServerConfig(providerCfg)
      const prompt = yield* SessionPrompt.Service
      const sessions = yield* Session.Service
      const session = yield* sessions.create({
        title: "Single provider call",
        permission: [{ permission: "*", pattern: "*", action: "allow" }],
      })
      yield* prompt.prompt({
        sessionID: session.id,
        agent: "build",
        noReply: true,
        parts: [{ type: "text", text: "Inspect two things, then report." }],
      })
      // N = 2 tool rounds, then a final text step: the chained turn must pull
      // three per-step HTTP requests.
      yield* llm.tool("glob", { pattern: "*.round-one" })
      yield* llm.tool("glob", { pattern: "*.round-two" })
      yield* llm.text("all rounds done")

      yield* prompt.loop({ sessionID: session.id })

      // `llm.calls` counts HTTP requests to the provider (one per SDK step).
      expect(yield* llm.calls).toBe(3)
      // One `streamText` invocation creates exactly one assistant message.
      // Before H1 the outer loop re-entered per round and produced three.
      const messages = yield* sessions.messages({ sessionID: session.id })
      expect(assistantCount(messages)).toBe(1)
      const last = messages.findLast((message) => message.info.role === "assistant")
      if (last && last.info.role === "assistant") expect(last.info.finish).not.toBe("tool-calls")
    }),
  30000,
)